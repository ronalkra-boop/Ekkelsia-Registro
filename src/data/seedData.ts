interface RawSeedRow {
  id: string;
  codigo: string;
  nombres: string;
  apellidos: string;
  tipoDocumento: DocumentType;
  documentoIdentidad: string;
  fechaNacimiento: string;
  genero: Gender;
  estadoCivil: MaritalStatus;
  telefono: string;
  direccion: string;
  barrio: string;
  profesionOcupacion: string;
  procedenciaTipo: ProcedenciaType;
  iglesiaProcedencia: string;
  lugarProcedencia: string;
  discipuladoEstado: DiscipuladoEstado;
  cargo: string;
  bautizado: boolean;
  estadoMembresia: MembershipStatus;
  familiaId?: string;
  rolFamiliar?: string;
  ministerioId?: string;
  notasPastorales?: string;
}

function buildMember(r: RawSeedRow): Member {
  return {
    id: r.id,
    ownerUid: LOCAL_OWNER,
    codigoMiembro: r.codigo,
    nombres: r.nombres,
    apellidos: r.apellidos,
    tipoDocumento: r.tipoDocumento,
    documentoIdentidad: r.documentoIdentidad,
    fechaNacimiento: r.fechaNacimiento,
    genero: r.genero,
    estadoCivil: r.estadoCivil,
    telefono: r.telefono,
    email: '',
    direccion: r.direccion,
    barrio: r.barrio,
    profesionOcupacion: r.profesionOcupacion,
    procedenciaTipo: r.procedenciaTipo,
    iglesiaProcedencia: r.iglesiaProcedencia,
    lugarProcedencia: r.lugarProcedencia,
    discipuladoEstado: r.discipuladoEstado,
    cargo: r.cargo,
    familiaId: r.familiaId ?? '',
    rolFamiliar: r.rolFamiliar ?? '',
    estadoMembresia: r.estadoMembresia,
    bautizado: r.bautizado,
    fechaBautismo: '',
    fechaIngreso: '2026-01-15',
    ministerioId: r.ministerioId ?? '',
    notasPastorales: r.notasPastorales ?? '',
  };
}

